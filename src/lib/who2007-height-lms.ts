export const WHO_2007_HEIGHT_LMS: readonly Row[] = RAW.trim().split("\n").map((line) => {
  const [month, boyM, boyS, girlM, girlS] = line.split(",").map(Number);
  return { month, boyM, boyS, girlM, girlS };
});

const Z = {
  p3: -1.880793608151251,
  p15: -1.03643338949379,
  p50: 0,
  p85: 1.03643338949379,
  p97: 1.880793608151251,
} as const;

function interpolate(months: number, sex: GrowthReferenceSex) {
  if (months < 61 || months > 228) return null;
  const lowMonth = Math.max(61, Math.min(228, Math.floor(months)));
  const highMonth = Math.max(61, Math.min(228, Math.ceil(months)));
  const low = WHO_2007_HEIGHT_LMS[lowMonth - 61];
  const high = WHO_2007_HEIGHT_LMS[highMonth - 61];
  const t = highMonth === lowMonth ? 0 : (months - lowMonth) / (highMonth - lowMonth);
  const mLow = sex === "BOY" ? low.boyM : low.girlM;
  const mHigh = sex === "BOY" ? high.boyM : high.girlM;
  const sLow = sex === "BOY" ? low.boyS : low.girlS;
  const sHigh = sex === "BOY" ? high.boyS : high.girlS;
  return { L: 1, M: mLow + (mHigh - mLow) * t, S: sLow + (sHigh - sLow) * t };
}

function lmsValue(L: number, M: number, S: number, z: number) {
  if (Math.abs(L) < 1e-9) return M * Math.exp(S * z);
  const base = 1 + L * S * z;
  return base > 0 ? M * Math.pow(base, 1 / L) : null;
}

export function whoHeightPercentiles(ageMonths: number, sex: GrowthReferenceSex) {
  const lms = interpolate(ageMonths, sex);
  if (!lms) return null;
  const value = (z: number) => {
    const v = lmsValue(lms.L, lms.M, lms.S, z);
    return v === null ? null : Math.round(v * 10) / 10;
  };
  return { p3: value(Z.p3), p15: value(Z.p15), p50: value(Z.p50), p85: value(Z.p85), p97: value(Z.p97) };
}


/** Curvas oficiais de altura por idade OMS 2007, em escores-Z (L=1 para altura). */
export function whoHeightZCurves(ageMonths: number, sex: GrowthReferenceSex) {
  const lms = interpolate(ageMonths, sex);
  if (!lms) return null;
  const value = (z: number) => {
    const result = lmsValue(lms.L, lms.M, lms.S, z);
    return result === null ? null : Math.round(result * 10) / 10;
  };
  return {
    whoZMinus3: value(-3),
    whoZMinus2: value(-2),
    whoZMinus1: value(-1),
    whoZ0: value(0),
    whoZPlus1: value(1),
    whoZPlus2: value(2),
    whoZPlus3: value(3),
  };
}

/** Posição estatística na referência OMS para altura por idade, sem interpretação clínica. */
export function whoHeightZScore(ageMonths: number, sex: GrowthReferenceSex, heightCm: number) {
  const lms = interpolate(ageMonths, sex);
  if (!lms || !Number.isFinite(heightCm) || heightCm <= 0) return null;
  const value = (Math.pow(heightCm / lms.M, lms.L) - 1) / (lms.L * lms.S);
  return Number.isFinite(value) ? Math.round(value * 100) / 100 : null;
}
